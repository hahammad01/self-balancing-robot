    int16_t az = (int16_t)((buf[4] << 8) | buf[5]);
    HAL_I2C_Mem_Read(&hi2c1, MPU6050_ADDR, REG_GYRO_XOUT_H,  I2C_MEMADD_SIZE_8BIT, buf, 6, 100);
