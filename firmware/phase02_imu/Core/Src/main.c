// ---- Kalman filter: 2 states (angle, gyro bias) ----
float Q_angle   = 0.001f;   // process noise on the angle
float Q_bias    = 0.003f;   // process noise on the bias
float R_measure = 0.1f;    // accel measurement noise
float kalAngle  = 0.0f;     // filtered angle (output)
float kalBias   = 0.0f;     // estimated gyro bias (tracked live)
float P[2][2]   = { {0, 0}, {0, 0} };   // uncertainty of [angle, bias]

float kalman(float newAngle, float newRate, float dt) {
    // ---- PREDICT: advance the angle with the gyro, grow the uncertainty ----
    float rate = newRate - kalBias;     // remove the estimated bias
    kalAngle += dt * rate;              // integrate to predict

    P[0][0] += dt * (dt*P[1][1] - P[0][1] - P[1][0] + Q_angle);
    P[0][1] -= dt * P[1][1];
    P[1][0] -= dt * P[1][1];
    P[1][1] += Q_bias * dt;

    // ---- UPDATE: correct with the accelerometer ----
    float S  = P[0][0] + R_measure;     // total expected error
    float K0 = P[0][0] / S;             // Kalman gain for angle
    float K1 = P[1][0] / S;             // Kalman gain for bias

    float y = newAngle - kalAngle;      // innovation: measured - predicted
    kalAngle += K0 * y;                 // correct angle
    kalBias  += K1 * y;                 // correct bias

    float P00 = P[0][0], P01 = P[0][1]; // shrink the uncertainty
    P[0][0] -= K0 * P00;
    P[0][1] -= K0 * P01;
    P[1][0] -= K1 * P00;
    P[1][1] -= K1 * P01;

    return kalAngle;
}
